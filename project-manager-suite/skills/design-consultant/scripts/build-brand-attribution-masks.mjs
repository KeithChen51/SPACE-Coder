#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const SKILL_ROOT = resolve(SCRIPT_DIR, "..");
const ASSET_ROOT = join(SKILL_ROOT, "templates/brand-attribution");
const LIGHT_SOURCE = join(ASSET_ROOT, "space-mark-parametric-orbit-accent.svg");
const DARK_SOURCE = join(ASSET_ROOT, "space-mark-parametric-orbit-accent-dark.svg");
const OUTPUTS = {
  wordmark: join(ASSET_ROOT, "space-mark-parametric-wordmark-mask.svg"),
  accent: join(ASSET_ROOT, "space-mark-parametric-accent-mask.svg"),
  focus: join(ASSET_ROOT, "space-mark-parametric-focus-mask.svg"),
  orbit: join(ASSET_ROOT, "space-mark-parametric-orbit-mask.svg"),
  orbitBack: join(ASSET_ROOT, "space-mark-parametric-orbit-back-mask.svg"),
  orbitFront: join(ASSET_ROOT, "space-mark-parametric-orbit-front-mask.svg"),
  runtime: join(SKILL_ROOT, "templates/react-runtime/src/brand-attribution-masks.ts"),
};
const ACCENT = "#FE5205";
const FOCUS_PATH = /<path\s+d="M 632\.8 17\.2[\s\S]*?<\/path>|<path\s+d="M 632\.8 17\.2[\s\S]*?\/>/;

function parseSvg(source, path) {
  const viewBox = source.match(/\bviewBox="([^"]+)"/)?.[1];
  const groups = [...source.matchAll(/^\s{2}<g\s+fill="([^"]+)"[\s\S]*?^\s{2}<\/g>/gm)].map((match) => ({
    color: match[1].toUpperCase(),
    markup: match[0],
  }));

  if (!viewBox) throw new Error(`${path} is missing viewBox.`);
  if (groups.length !== 3) throw new Error(`${path} must contain exactly three top-level color groups.`);
  return { viewBox, groups };
}

function asMask(group) {
  return group.markup.replace(/fill="[^"]+"/, 'fill="#000000"');
}

function renderMask(viewBox, groups) {
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" aria-hidden="true" focusable="false">`,
    ...groups.map(asMask),
    "</svg>",
    "",
  ].join("\n");
}

function renderRuntimeModule(wordmark, focus, orbit, orbitBack, orbitFront) {
  const dataUrl = (source) => `url(\"data:image/svg+xml;base64,${Buffer.from(source).toString("base64")}\")`;
  return [
    "// Generated by scripts/build-brand-attribution-masks.mjs. Do not edit directly.",
    `export const SPACE_WORDMARK_MASK = ${JSON.stringify(dataUrl(wordmark))};`,
    `export const SPACE_FOCUS_MASK = ${JSON.stringify(dataUrl(focus))};`,
    `export const SPACE_ORBIT_MASK = ${JSON.stringify(dataUrl(orbit))};`,
    `export const SPACE_ORBIT_BACK_MASK = ${JSON.stringify(dataUrl(orbitBack))};`,
    `export const SPACE_ORBIT_FRONT_MASK = ${JSON.stringify(dataUrl(orbitFront))};`,
    "",
  ].join("\n");
}

function splitFocusSymbol(group, path) {
  const match = group.markup.match(FOCUS_PATH);
  if (!match) throw new Error(`${path} is missing the approved SPACE A focus path.`);
  return {
    neutralMarkup: group.markup.replace(match[0], "").replace(/[ \t]+$/gm, ""),
    focusMarkup: `<g fill="${ACCENT}">\n    ${match[0]}\n  </g>`,
  };
}

async function expectedMasks() {
  const [lightSource, darkSource] = await Promise.all([
    readFile(LIGHT_SOURCE, "utf8"),
    readFile(DARK_SOURCE, "utf8"),
  ]);
  const light = parseSvg(lightSource, LIGHT_SOURCE);
  const dark = parseSvg(darkSource, DARK_SOURCE);
  const lightGeometry = light.groups.map(asMask);
  const darkGeometry = dark.groups.map(asMask);

  if (light.viewBox !== dark.viewBox || JSON.stringify(lightGeometry) !== JSON.stringify(darkGeometry)) {
    throw new Error("Light and dark approved SVG assets must share identical geometry.");
  }

  const [orbitBackGroup, wordmarkGroup, orbitFrontGroup] = light.groups;
  if (orbitBackGroup.color !== ACCENT || wordmarkGroup.color === ACCENT || orbitFrontGroup.color !== ACCENT) {
    throw new Error(`Approved SVG painter order must be ${ACCENT} back orbit, neutral wordmark, ${ACCENT} front orbit.`);
  }

  const { neutralMarkup, focusMarkup } = splitFocusSymbol(wordmarkGroup, LIGHT_SOURCE);

  const wordmark = renderMask(light.viewBox, [{ markup: neutralMarkup }]);
  const focus = renderMask(light.viewBox, [{ markup: focusMarkup }]);
  const orbitBack = renderMask(light.viewBox, [orbitBackGroup]);
  const orbitFront = renderMask(light.viewBox, [orbitFrontGroup]);
  const orbit = renderMask(light.viewBox, [orbitBackGroup, orbitFrontGroup]);
  const accent = renderMask(light.viewBox, [orbitBackGroup, { markup: focusMarkup }, orbitFrontGroup]);
  return {
    [OUTPUTS.wordmark]: wordmark,
    [OUTPUTS.accent]: accent,
    [OUTPUTS.focus]: focus,
    [OUTPUTS.orbit]: orbit,
    [OUTPUTS.orbitBack]: orbitBack,
    [OUTPUTS.orbitFront]: orbitFront,
    [OUTPUTS.runtime]: renderRuntimeModule(wordmark, focus, orbit, orbitBack, orbitFront),
  };
}

async function main() {
  const command = process.argv[2] || "build";
  if (!new Set(["build", "check"]).has(command)) {
    throw new Error(`Unknown command: ${command}. Use build or check.`);
  }

  const masks = await expectedMasks();
  const results = [];
  for (const [path, expected] of Object.entries(masks)) {
    if (command === "build") {
      await writeFile(path, expected, "utf8");
      results.push({ path, status: "built" });
      continue;
    }

    let actual = "";
    try {
      actual = await readFile(path, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    results.push({ path, status: actual === expected ? "current" : "stale" });
  }

  process.stdout.write(`${JSON.stringify({ command, results })}\n`);
  if (results.some((result) => result.status === "stale")) process.exitCode = 2;
}

main().catch((error) => {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
});
