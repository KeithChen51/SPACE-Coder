function replaceRequired(source, from, to, file) {
  if (!source.includes(from)) {
    throw new Error(`${file} 的本地化锚点缺失：${from.slice(0, 80)}`);
  }
  return source.replaceAll(from, to);
}

export function localizeGallerySource(source, file) {
  const staticReplacements = STATIC_REPLACEMENTS[file];
  const dynamicReplacements = DYNAMIC_REPLACEMENTS[file];
  if (!staticReplacements || !dynamicReplacements) throw new Error(`没有为 ${file} 配置完整的可视化本地化规则`);
  const localized = staticReplacements.reduce(
    (localized, [from, to]) => replaceRequired(localized, from, to, file),
    source,
  );
  return dynamicReplacements.reduce(
    (result, [from, to]) => replaceRequired(result, from, to, file),
    localized,
  );
}

export function localizedSystemLabel(system) {
  return SYSTEM_LABELS[system] || system;
}

export function localizePresetMetadata(preset) {
  const copy = PRESET_COPY[preset.id];
  if (!copy) throw new Error(`缺少 ${preset.id} 的中文 preset 文案`);
  const [name, cardTitle] = copy;
  return {
    ...preset,
    sourceName: preset.name,
    name,
    sourceSystemLabel: preset.systemLabel,
    systemLabel: localizedSystemLabel(preset.system),
    sourceCardTitle: preset.cardTitle,
    cardTitle,
    ...(preset.system === "interactive" ? {
      occasion: "整页交互",
      readerTime: "交互探索",
    } : {}),
  };
}

